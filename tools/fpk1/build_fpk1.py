#!/usr/bin/env python3
"""Build QEMU, the GLES bridge and FPK1 media into a new directory with run.sh.

Usage:
  python3 tools/fpk1/build_fpk1.py --archive <FPK1 update.zip> --output ../fpk1-build
  bash ../fpk1-build/run.sh            # console in the terminal; frames and the KSS log in a window

Outputs (the directory must not exist; nothing is overwritten):
  qemu/qemu-system-arm    emulator built from this checkout (or --qemu copied)
  bridge/                 guest libEGL.so/libGLESv2.so shim (1440x540) and glhost
  media/emmc.img          synthetic eMMC (stage2_nand, stage3, app, blank QNX6)
  venv/                   Python with lzokay, sharing system PySide6
  runs/<time>/            per-run console/QEMU/glhost logs and frames
  build-manifest.json     source commit, archive hash, tool versions
The firmware archive is referenced, not copied. Synthetic board identity,
NOR and eMMC layout are research inputs, not a device image.
"""
import argparse
import hashlib
import json
from pathlib import Path
import shlex
import shutil
import subprocess
import sys

TOOLS = Path(__file__).resolve().parent
REPO = TOOLS.parents[1]


def run(command, **kwargs):
    print('+ ' + shlex.join(map(str, command)), flush=True)
    subprocess.run(list(map(str, command)), check=True, **kwargs)


def build_qemu(output, jobs):
    build = output / 'qemu-build'
    build.mkdir()
    run([REPO / 'configure', '--target-list=arm-softmmu', '--disable-docs', '--disable-werror'], cwd=build)
    run(['make', '-C', build, f'-j{jobs}', 'qemu-system-arm'])
    return build / 'qemu-system-arm'


def build_bridge(output, arm_prefix):
    bridge = output / 'bridge'
    bridge.mkdir()
    shim = REPO / 'tools/mhi2/glforward/guest/gl_shim.c'
    run([arm_prefix + 'gcc', '-mfloat-abi=soft', '-mcpu=cortex-a9', '-marm', '-fPIC', '-ffreestanding',
         '-fno-builtin', '-O2', '-DGLBRIDGE_DEFAULT_W=1440', '-DGLBRIDGE_DEFAULT_H=540',
         '-c', shim, '-o', bridge / 'gl-shim.o'])
    for name in ('libGLESv2.so', 'libEGL.so'):
        run([arm_prefix + 'ld', '-shared', '--hash-style=sysv', '-soname', name,
             '-o', bridge / name, bridge / 'gl-shim.o'])
    run(['bash', REPO / 'tools/mhi2/glforward/build_host.sh', bridge / 'glhost'])


LAUNCHER = r'''#!/usr/bin/env bash
# Generated by tools/fpk1/build_fpk1.py. Boots FPK1 with the GLES bridge.
# Always opens the viewer, which also runs the KSS peer and shows its log under
# the frame. Options: --seconds N (default 1800), plus any run_stage1_console.py
# option. Ctrl-C stops the emulator.
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
seconds=1800
args=()
while (($#)); do
    case "$1" in
        --seconds) seconds=$2; shift 2 ;;
        *) args+=("$1"); shift ;;
    esac
done
run="$here/runs/$(date +%Y%m%d-%H%M%S)"
mkdir -p "$run"
export MHI2_GL_WIDTH=1440 MHI2_GL_HEIGHT=540
# GLSL for the firmware's Tegra binaries, made by tools/fpk1/research/shader-translate.
export MHI2_SHADER_CACHE=$here/research-artifacts/shader-translate/cache
# GR3D is not emulated; GLES goes through the bridge, native 3D jobs retire empty.
export TEGRA_GR3D_DISCARD=1
# Multi-threaded TCG: with -icount shift=0 (round-robin vCPUs) procnto
# randomly corrupts thread contexts and shuts down within minutes.
echo "FPK1 run: logs and frames in $run"
exec "$here/venv/bin/python" @REPO@/tools/fpk1/run_stage1_console.py @ARCHIVE@ \
    --qemu "$here/qemu/qemu-system-arm" --tcg-thread multi --board-info \
    --emmc "$here/media/emmc.img" \
    --stage2-replace lib/libEGL.so="$here/bridge/libEGL.so" \
    --stage2-replace lib/libGLESv2.so="$here/bridge/libGLESv2.so" \
    --glhost "$here/bridge/glhost" --gl-frames "$run/frames" --viewer --kss \
    --seconds "$seconds" --keep-dir "$run" --json "$run/result.json" ${args[@]+"${args[@]}"}
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--archive', required=True, type=Path, help='FPK1 update ZIP')
    parser.add_argument('--output', required=True, type=Path, help='new build directory')
    parser.add_argument('--qemu', type=Path, help='reuse an already built qemu-system-arm')
    parser.add_argument('--jobs', type=int, default=8)
    parser.add_argument('--arm-prefix', default='arm-none-eabi-')
    args = parser.parse_args()
    archive, output = args.archive.resolve(), args.output.resolve()
    if output.exists():
        raise SystemExit(f'{output} exists; choose a new output directory')
    output.mkdir(parents=True)
    output.chmod(0o700)

    run([sys.executable, '-m', 'venv', '--system-site-packages', output / 'venv'])
    run([output / 'venv/bin/pip', '-q', 'install', 'lzokay'])

    (output / 'qemu').mkdir()
    qemu = args.qemu.resolve() if args.qemu else build_qemu(output, args.jobs)
    shutil.copy2(qemu, output / 'qemu/qemu-system-arm')
    build_bridge(output, args.arm_prefix)

    (output / 'media').mkdir()
    run([output / 'venv/bin/python', TOOLS / 'create_fpk1_emmc.py', archive, output / 'media/emmc.img'],
        stdout=(output / 'media/emmc.json').open('w'))
    (output / 'runs').mkdir()

    launcher = output / 'run.sh'
    launcher.write_text(LAUNCHER.replace('@REPO@', shlex.quote(str(REPO)))
                        .replace('@ARCHIVE@', shlex.quote(str(archive))))
    launcher.chmod(0o755)
    with archive.open('rb') as stream:
        archive_hash = hashlib.file_digest(stream, 'sha256').hexdigest()
    commit = subprocess.run(['git', '-C', str(REPO), 'rev-parse', 'HEAD'],
                            capture_output=True, text=True).stdout.strip()
    report = dict(source_commit=commit, archive=str(archive), archive_sha256=archive_hash,
                  qemu=str(qemu), python=sys.version,
                  arm_compiler=subprocess.check_output([args.arm_prefix + 'gcc', '--version'],
                                                       text=True).splitlines()[0])
    (output / 'build-manifest.json').write_text(json.dumps(report, indent=2) + '\n')
    print('Ready: bash ' + shlex.quote(str(launcher)))


if __name__ == '__main__':
    main()
